#!/usr/bin/env python3
"""Bundle the pinned, reviewed console-only Moonlight-nx2 modules as classic JS.

This intentionally supports only the selected snapshot's simple module syntax.
It never includes the PC protocol helper, transport service, or launcher.
"""
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'third_party/civ-vulkan'
OUT = ROOT / 'vendor/civ-vulkan.js'
PUBLIC = {
 'display':'src/streamer/civ7/display.js', 'callPlan':'src/streamer/civ7/call-plan.js',
 'pipelineHelpers':'src/streamer/civ7/pipelines.js', 'compat':'src/streamer/civ7/compat.js',
 'ring':'src/streamer/shared/ring.js', 'refreshRecord':'src/streamer/civ7/refresh-rate-record.js',
 'refresh':'src/streamer/civ7/refresh-rate.js',
 'compatTable':'src/streamer/civ7/compat-functions.json',
 'filesystemTable':'src/streamer/civ7/filesystem-functions.json'
}
STUBS = {
    'node:path': 'return {default:{join:function(){return Array.from(arguments).join("/");}}};',
    'node:fs/promises': 'return {default:{readFile:async function(path){var name=path.split("/").pop(),files=g.__civNanoVGFiles;if(!["compatibility-module.json","vulkan-display.json"].includes(name)||!files||!files[name])throw Error("No local NanoVG record: "+name);return JSON.stringify(files[name]);}}};',
    'node:timers/promises': 'return {setTimeout:function(ms){return new Promise(function(r){setTimeout(r,ms);});}};',
    'src/streamer/civ7/protocol.js': 'return {replyInteger:function(r,k){return BigInt(r[k]);},replyString:function(r,k){if(typeof r[k]!=="string")throw Error("Invalid reply string");return r[k];},replyArray:function(r,k){if(!Array.isArray(r[k]))throw Error("Invalid reply array");return r[k];}};',
}


def build():
    manifest = json.loads((SOURCE / 'SOURCE.json').read_text())
    for name, expected in manifest['sha256'].items():
        if hashlib.sha256((SOURCE / name).read_bytes()).hexdigest() != expected:
            raise ValueError(f'Pinned Vulkan source changed: {name}')
    from classic_modules import compile_graph
    factories=compile_graph(SOURCE,PUBLIC.values(),STUBS)
    output = '/* Generated by tools/build-vulkan.py. Moonlight-nx2 reference subset; see bundled notices. */\n(function(g){"use strict";\nconst Buffer=g.CivNanoVGBuffer;\nconst __factories={\n'
    output += ',\n'.join(json.dumps(name) + ':function(){\n' + text + '\n}' for name, text in factories.items())
    output += '\n};const __cache={};function __require(name){if(!__cache[name]){if(!__factories[name])throw Error("Missing native UI module: "+name);__cache[name]=__factories[name]();}return __cache[name];}\n'
    output += 'const modules={' + ','.join(k + ':__require(' + json.dumps(v) + ')' + ('.default' if v.endswith('.json') else '') for k, v in PUBLIC.items()) + '};\n'
    output += 'g.CivNanoVGModules=modules;\n})(typeof window!=="undefined"?window:globalThis);\n'
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(output)
    print(f'Vulkan runtime: {OUT} ({len(output.encode()):,} bytes; {len(factories)} modules; no PC service)')


if __name__ == '__main__':
    build()
